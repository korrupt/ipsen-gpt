#!/usr/bin/env bash
# Writes an Nginx snippet that restores real client IPs from Cloudflare's
# CF-Connecting-IP header, trusting it only from Cloudflare's published ranges.
#   usage: cloudflare-realip.sh [output-file]   (default /etc/nginx/conf.d/cloudflare-realip.conf)
set -euo pipefail

OUT=${1:-/etc/nginx/conf.d/cloudflare-realip.conf}
v4=$(curl -fsS --max-time 15 https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS --max-time 15 https://www.cloudflare.com/ips-v6)

cidr_re='^[0-9a-fA-F:.]+/[0-9]+$'
{
  echo "# Generated by cloudflare-realip.sh on $(date -u +%F). Re-run if Cloudflare changes its ranges."
  for cidr in $v4 $v6; do
    [[ $cidr =~ $cidr_re ]] || { echo "unexpected entry from Cloudflare: $cidr" >&2; exit 1; }
    echo "set_real_ip_from $cidr;"
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$OUT.tmp"

count=$(grep -c '^set_real_ip_from' "$OUT.tmp")
(( count >= 10 )) || { echo "only $count ranges fetched, refusing to write" >&2; rm -f "$OUT.tmp"; exit 1; }
mv "$OUT.tmp" "$OUT"
echo "wrote $count Cloudflare ranges to $OUT"
